#!/usr/bin/env node
/**
 * Generates .motion-manifest.json from the motion registry.
 *
 * This is the machine-readable half of the motion docs: every preset with its
 * parameters, its intent, its cost and its resolved duration token, plus the
 * token scale and the attribute contract. An agent choosing motion for a design
 * reads THIS, not a hand-written list that drifts the moment a preset is added.
 *
 * Gitignored and regenerated on install, the same way PROJECT-MAP.md is.
 *
 * Run: yarn motion:manifest
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import {
  listMotionPresets,
  motionCssFrom,
  motionPresetForViewport,
  ALLOWED_FROM_PROPERTIES,
  DEFAULT_PRESET,
  MOBILE_MAX_WIDTH,
} from "../src/js/modules/motion-presets.js";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "../.motion-manifest.json");
const TOKENS_FILE = resolve(here, "../snippets/css-variables.liquid");

/** Pull the token values out of css-variables so the manifest states real numbers. */
function readTokens() {
  const text = readFileSync(TOKENS_FILE, "utf8");
  const tokens = {};
  for (const match of text.matchAll(/(--motion-[a-z-]+):\s*([^;]+);/g)) {
    // First declaration wins: later ones are the small-screen overrides, which
    // are reported separately.
    if (!(match[1] in tokens)) tokens[match[1]] = match[2].trim();
  }
  return tokens;
}

const manifest = {
  $comment: "GENERATED by scripts/build-motion-manifest.mjs — do not edit. Source: src/js/modules/motion-presets.js",
  defaultPreset: DEFAULT_PRESET,
  animatableProperties: ALLOWED_FROM_PROPERTIES,
  tokens: readTokens(),
  mobile: {
    maxWidth: MOBILE_MAX_WIDTH,
    note: "Below this width --motion-reveal, --motion-stagger and --motion-distance are overridden. A preset may name its own small-screen kind with `mobile`; that is an authoring choice and it outranks the automatic step-down. Absent it, kinds are NOT swapped out: the step-down only applies to a preset that is cost:high AND already fades, because turning a transform-only entrance into a fade would hide content that was never hidden. A preset that does not fade MAY name one that does: that is the authoring choice, and registerMotionPreset() only rejects an alternative that is unregistered or is the preset itself. A fading element is never an LCP candidate, so weigh it. Each preset's onMobile field states what it actually becomes.",
  },
  attributes: {
    "data-motion": "Preset name. Required for anything to animate.",
    "data-motion-delay": "Milliseconds before this element starts.",
    "data-motion-stagger": "motion-group only. Step between cells in ms; 0 means all together.",
    "data-motion-trigger": "inview (default) | load | manual.",
    "data-motion-repeat": "Re-arm when it scrolls out of view.",
    "data-instantly": "Do not wait for images inside to load.",
    "data-motion-hold": "Prestage only; wait for replay().",
    "data-motion-off": "Opt this element out.",
    "data-motion-disabled": "On an ancestor: opt out the whole subtree.",
    "data-motion-essential": "Exempt from the global reduced-motion floor. Marquee and spinners only.",
    "data-motion-from":
      "WRITTEN BY THE RUNTIME, never by you. Names the preset whose start state the generated stylesheet should hold this element at, which is how the start state stays a CSS concern and honours a scoped --motion-distance. An element still carrying it is one the stylesheet is holding at opacity 0 — if content is invisible, look here first.",
  },
  elements: {
    "motion-component": "One element. Use for a heading, an image, a block.",
    'div[is="motion-group"]':
      "A LIST — placed ON the existing grid or carousel row. One budget slot for the whole list; staggers its cells. Always prefer this over one motion-component per card.",
  },
  api: {
    "FoxTheme.motion.replayWithin(container)":
      "Replay every motion element at or inside a container — modal, filter, morph.",
    "FoxTheme.motion.replay(target)": "Reset and run again.",
    "FoxTheme.motion.reveal(target)": "Final state, no animation. The always-safe exit.",
    "FoxTheme.motion.reset(target)": "Back to the start state without playing.",
    "FoxTheme.motion.disable(target)": "Opt out and reveal.",
    "FoxTheme.motion.enable(target)": "Opt back in.",
    "FoxTheme.motion.registerPreset(name, def)": "Fork extension point — add a kind without editing core.",
  },
  presets: listMotionPresets().map((preset) => ({
    name: preset.name,
    label: preset.label ?? preset.name,
    intent: preset.intent ?? "",
    cost: preset.cost ?? "low",
    duration: preset.duration ?? "reveal",
    durationToken: `--motion-${preset.duration ?? "reveal"}`,
    from: preset.from ?? {},
    css: motionCssFrom(preset),
    onMobile: motionPresetForViewport(preset.name, true),
    deprecated: preset.deprecated ?? null,
  })),
};

const output = JSON.stringify(manifest, null, 2) + "\n";

if (process.argv.includes("--check")) {
  let previous = null;
  try {
    previous = readFileSync(OUT, "utf8");
  } catch {}
  if (previous !== output) {
    console.error("✗ .motion-manifest.json is stale — run `yarn motion:manifest`.");
    process.exit(1);
  }
  console.log("✓ motion manifest matches the registry.");
} else {
  writeFileSync(OUT, output);
  console.log(`✓ wrote .motion-manifest.json (${manifest.presets.length} presets)`);
}
